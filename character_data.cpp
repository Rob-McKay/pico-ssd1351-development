extern "C" void write_char_at(char c, int x, int y, uint16_t fg_colour, uint16_t bg_colour, uint16_t buffer[], int width, int height)
{
    if ((x < 0) || (x + CellWidth > width) || (y < 0) || (y + CellHeight > height))
    {
        // Character would be drawn out of bounds, do nothing
        return;
    }

    if ((uint8_t)c < LowerCharactersStart || (uint8_t)c > LowerCharactersEnd)
    {
        // Character not in font set, treat as space
        c = ' ';
    }

    const auto CharacterData = lowerCharacters[(uint8_t)(c - LowerCharactersStart)];

    for (int cy = 0; cy < CellHeight; ++cy)
    {
        uint16_t row = CharacterData[cy];
        uint16_t mask = 1U << (CellWidth - 1);

        for (int cx = 0; cx < CellWidth; ++cx)
        {
            buffer[(y + cy) * width + (x + cx)] = (row & mask) ? fg_colour : bg_colour;
            mask >>= 1;
        }
    }
}



extern "C" void write_string_at(const char* str, int x, int y, uint16_t fg_colour, uint16_t bg_colour, uint16_t buffer[], int width, int height)
{
    int cursor_x = x;
    int cursor_y = y;

    for (const char* p = str; *p != '\0'; ++p)
    {
        auto ch = *p;
        if (ch < LowerCharactersStart) // Handle control characters
        {
            if (ch == '\n')
            {
                cursor_x = x;
                cursor_y += CellHeight;
            }
            continue;
        }

        write_char_at(ch, cursor_x, cursor_y, fg_colour, bg_colour, buffer, width, height);
        cursor_x += CellWidth;

        if (cursor_x + CellWidth > width)
        {
            cursor_x = x;
            cursor_y += CellHeight;
        }

        if (cursor_y + CellHeight > height)
        {
            break; // No more space to draw
        }
    }   
}